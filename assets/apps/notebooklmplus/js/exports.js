import { downloadText } from './utils.js';

function safeName(name='artifact') {
  const cleaned = String(name).replace(/[\\/:*?"<>|]+/g, '-').replace(/\s+/g, ' ').trim();
  return (cleaned || 'artifact').slice(0, 120);
}
function xmlEscape(s='') { return String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&apos;'); }
function downloadBlob(filename, blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a'); a.href = url; a.download = filename; document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

export function artifactToCsv(data) {
  if (!data || !Array.isArray(data.rows)) return '';
  const esc = v => { const s = String(v ?? ''); return /[",\n]/.test(s) ? `"${s.replaceAll('"','""')}"` : s; };
  return [(data.columns || []).map(esc).join(','), ...data.rows.map(r => (r || []).map(esc).join(','))].join('\n');
}

export async function exportDocx(title, text) {
  if (!window.JSZip) throw new Error('JSZip is required for DOCX export.');
  const zip = new window.JSZip();
  const paragraphs = String(text || '').split(/\n+/).filter(Boolean).map(line => `<w:p><w:r><w:t xml:space="preserve">${xmlEscape(line)}</w:t></w:r></w:p>`).join('');
  zip.file('[Content_Types].xml', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>`);
  zip.folder('_rels').file('.rels', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>`);
  zip.folder('word').file('document.xml', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:rPr><w:b/></w:rPr><w:t>${xmlEscape(title)}</w:t></w:r></w:p>${paragraphs}<w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr></w:body></w:document>`);
  const blob = await zip.generateAsync({ type:'blob', mimeType:'application/vnd.openxmlformats-officedocument.wordprocessingml.document' });
  downloadBlob(`${safeName(title)}.docx`, blob);
}

export function exportXlsx(title, data) {
  if (!window.XLSX) throw new Error('SheetJS is required for XLSX export.');
  const rows = [data?.columns || ['Content'], ...(Array.isArray(data?.rows) ? data.rows : [[String(data?.summary || '')]])];
  const ws = window.XLSX.utils.aoa_to_sheet(rows);
  const wb = window.XLSX.utils.book_new();
  window.XLSX.utils.book_append_sheet(wb, ws, 'NotebookLM+');
  window.XLSX.writeFile(wb, `${safeName(title)}.xlsx`, { compression:true });
}

export async function exportPptx(title, data) {
  if (!window.PptxGenJS) throw new Error('PptxGenJS failed to load. Use Markdown/HTML export or reload while online.');
  const pptx = new window.PptxGenJS();
  pptx.layout = 'LAYOUT_WIDE';
  pptx.author = 'NotebookLM+'; pptx.subject = title; pptx.title = title; pptx.company = 'NotebookLM+';
  const titleSlide = pptx.addSlide();
  titleSlide.addText(title, { x:0.7, y:2.2, w:12, h:1, fontSize:30, bold:true, margin:0.05 });
  titleSlide.addText('Generated by NotebookLM+', { x:0.7, y:3.35, w:10, h:0.4, fontSize:13, color:'666666' });
  for (const row of data?.slides || []) {
    const slide = pptx.addSlide();
    slide.addText(String(row.title || ''), { x:0.55, y:0.35, w:12.2, h:0.65, fontSize:24, bold:true, margin:0.03 });
    const bullets = (row.bullets || []).slice(0,12).map(b => ({ text:String(b), options:{ bullet:{ indent:18 }, hanging:4, breakLine:true } }));
    if (bullets.length) slide.addText(bullets, { x:0.8, y:1.25, w:11.6, h:5.3, fontSize:18, breakLine:true, valign:'top', margin:0.05 });
    if (row.speakerNotes && slide.addNotes) slide.addNotes(String(row.speakerNotes));
  }
  await pptx.writeFile({ fileName:`${safeName(title)}.pptx` });
}

export function exportPdf(title, text) {
  const JsPDF = window.jspdf?.jsPDF;
  if (!JsPDF) throw new Error('jsPDF failed to load. Use HTML/DOCX export or reload while online.');
  const doc = new JsPDF({ unit:'pt', format:'a4' });
  const margin = 48; const width = doc.internal.pageSize.getWidth() - margin*2; const height = doc.internal.pageSize.getHeight();
  doc.setFontSize(18); doc.text(String(title), margin, 60);
  doc.setFontSize(10);
  const lines = doc.splitTextToSize(String(text || ''), width);
  let y = 88;
  for (const line of lines) {
    if (y > height - 50) { doc.addPage(); y = 50; }
    doc.text(line, margin, y); y += 14;
  }
  doc.save(`${safeName(title)}.pdf`);
}

export async function exportArtifact(artifact, format, plainText) {
  const title = artifact?.title || 'NotebookLM+ Artifact';
  const data = artifact?.data || null;
  const text = plainText || artifact?.content || '';
  switch (format) {
    case 'md': return downloadText(`${safeName(title)}.md`, text, 'text/markdown');
    case 'txt': return downloadText(`${safeName(title)}.txt`, text, 'text/plain');
    case 'html': return downloadText(`${safeName(title)}.html`, `<!doctype html><meta charset="utf-8"><title>${xmlEscape(title)}</title><pre style="white-space:pre-wrap;font-family:system-ui">${xmlEscape(text)}</pre>`, 'text/html');
    case 'json': return downloadText(`${safeName(title)}.json`, JSON.stringify(data ?? { title, content:text }, null, 2), 'application/json');
    case 'csv': return downloadText(`${safeName(title)}.csv`, artifactToCsv(data), 'text/csv');
    case 'docx': return exportDocx(title, text);
    case 'xlsx': return exportXlsx(title, data);
    case 'pptx': return exportPptx(title, data);
    case 'pdf': return exportPdf(title, text);
    default: throw new Error(`Unsupported export format: ${format}`);
  }
}
